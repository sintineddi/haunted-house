function notice(message) {
  const box = $("form-notice");
  box.textContent = message;
  box.hidden = !message;
  if (message) box.scrollIntoView({ behavior: "smooth", block: "center" });
}

async function shrink(file) {
  const bitmap = await createImageBitmap(file);
  const scale = Math.min(1, DRAWING_SIDE / Math.max(bitmap.width, bitmap.height));
  const canvas = document.createElement("canvas");
  canvas.width = Math.round(bitmap.width * scale);
  canvas.height = Math.round(bitmap.height * scale);
  canvas.getContext("2d").drawImage(bitmap, 0, 0, canvas.width, canvas.height);
  return new Promise((resolve) => canvas.toBlob(resolve, "image/jpeg", 0.9));
}

async function addDrawing(file) {
  if (!file) return;
  const draft = view.draft;
  const status = $("drawing-status");
  const button = $("drawing-button");
  status.textContent = say("reading_drawing");
  button.disabled = true;
  try {
    const image = await shrink(file);
    const response = await fetch(`/api/drawing?language=${draft.language}`, {
      method: "POST",
      headers: { "Content-Type": "image/jpeg" },
      body: image,
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || response.statusText);
    const sheet = data.sheet;
    const taken = new Set(draft.creatures.map((creature) => creature.room));
    const room = draft.rooms.find((each) => !taken.has(each.id) && each.id !== draft.start) || draft.rooms[0];
    draft.creatures.push({
      id: "",
      name: sheet.name,
      emoji: sheet.emoji,
      room: room.id,
      personality: [
        sheet.species,
        `${say("power")}${say("colon")}${sheet.power}`,
        `${say("weakness")}${say("colon")}${sheet.weakness}`,
        sheet.personality,
        `${say("scariness")}${say("colon")}${sheet.scariness}/5`,
      ]
        .map((part) => part.replace(/[.\s]+$/, ""))
        .join(". "),
      drawing: data.drawing,
      sheet,
    });
    buildForm();
    document.querySelector(".sheet")?.scrollIntoView({ behavior: "smooth", block: "center" });
  } catch (error) {
    status.textContent = say("error", { error: error.message });
    button.disabled = false;
  }
}

async function saveWorld(event) {
  event.preventDefault();
  const world = withFreshIds(structuredClone(view.draft));
  const response = await fetch("/api/world", {
    method: "PUT",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(world),
  });
  const data = await response.json().catch(() => ({ error: response.statusText }));
  if (!response.ok) return notice(data.error);
  view.world = data.world;
  view.language = view.world.language;
  applyLanguage();
  show("play");
  await newGame();
}

function openDesign() {
  if (view.busy) return;
  view.draft = structuredClone(view.world);
  view.language = view.draft.language;
  applyLanguage();
  buildForm();
  show("design");
}

function closeDesign() {
  view.language = view.state?.language || view.world.language;
  applyLanguage();
  show("play");
}

async function boot() {
  $("say").addEventListener("submit", (event) => {
    event.preventDefault();
    const action = $("action").value;
    $("action").value = "";
    act(action);
  });
  $("new-game").addEventListener("click", () => newGame());
  $("play-again").addEventListener("click", () => newGame());
  $("to-design").addEventListener("click", openDesign);
  $("world-form").addEventListener("submit", saveWorld);
  try {
    const data = await getJSON("/api/world");
    view.world = data.world;
    view.samples = data.samples;
    view.language = view.world.language;
    applyLanguage();
    const saved = store.get("haunted.game");
    if (saved && (await resume(saved))) return;
    await newGame();
  } catch (error) {
    $("log").append(el("div", { class: "error", text: say("error", { error: error.message }) }));
  }
}

boot();
