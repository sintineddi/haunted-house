function roomsSection(draft) {
  const { locked, key } = roles(draft);
  const parts = [el("h2", { text: say("rooms") }), el("p", { class: "hint", text: say("rooms_hint") })];
  for (const room of draft.rooms) {
    parts.push(
      card(
        line(
          field("emoji", room.emoji, (value) => ((room.emoji = value), refreshRoomOptions()), { small: true }),
          field(room.id === draft.start ? "room_entrance" : "room_name", room.name, (value) => {
            room.name = value;
            refreshRoomOptions();
          }),
        ),
        field("room_look", room.look, (value) => (room.look = value), { multiline: true }),
      ),
    );
  }
  if (locked && key) {
    parts.push(
      card(
        line(
          roomSelect(
            "locked_room",
            locked.id,
            (value) => {
              const lockedNow = draft.rooms.find((room) => room.locked_by);
              const keyId = lockedNow.locked_by;
              lockedNow.locked_by = "";
              draft.rooms.find((room) => room.id === value).locked_by = keyId;
            },
            [draft.start],
          ),
        ),
        line(
          field("emoji", key.emoji, (value) => (key.emoji = value), { small: true }),
          field("key_name", key.name, (value) => (key.name = value)),
          roomSelect("key_room", key.room, (value) => (key.room = value)),
        ),
      ),
    );
  }
  return parts;
}

